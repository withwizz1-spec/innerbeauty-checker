def init_ingredients_db():
    with get_connection() as conn:
        cur = conn.cursor()
        cur.execute(
            """
            CREATE TABLE IF NOT EXISTS ingredients (
                name TEXT PRIMARY KEY,
                category TEXT NOT NULL CHECK (category IN ('functional', 'additive', 'base'))
            )
            """
        )
        cur.execute(
            """
            CREATE TABLE IF NOT EXISTS ingredient_reports (
                id SERIAL PRIMARY KEY,
                name TEXT NOT NULL,
                suggested_category TEXT NOT NULL,
                reason TEXT,
                reported_at REAL NOT NULL
            )
            """
        )

        # 이미 만들어진 테이블에는 CHECK 제약이 예전 두 분류로 남아 있으므로 갱신
        # ('base' 분류를 나중에 추가했기 때문 — 새 DB에는 위 CREATE TABLE로 이미 반영됨)
        cur.execute("ALTER TABLE ingredients DROP CONSTRAINT IF EXISTS ingredients_category_check")
        cur.execute(
            """
            ALTER TABLE ingredients ADD CONSTRAINT ingredients_category_check
            CHECK (category IN ('functional', 'additive', 'base'))
            """
        )

        # 사전은 앱을 켤 때마다 "없는 것만" 채움 — 목록을 늘리면 다음 실행에 자동 반영되고,
        # 이미 있는 행은 건드리지 않아 나중에 손으로 고친 분류가 덮어써지지 않음
        rows = [(name, "functional") for name in FUNCTIONAL_INGREDIENTS]
        rows += [(name, "additive") for name in ADDITIVE_INGREDIENTS]
        rows += [(name, "base") for name in BASE_INGREDIENTS]
        cur.executemany(
            "INSERT INTO ingredients (name, category) VALUES (%s, %s) ON CONFLICT (name) DO NOTHING",
            rows,
        )


# 성분명 → 분류 전체 사전을 dict로 반환 (프론트엔드가 한 번에 받아서 캐싱해서 씀)
def get_all_categories() -> dict:
    with get_connection() as conn:
        cur = conn.cursor()
        cur.execute("SELECT name, category FROM ingredients")
        rows = cur.fetchall()
    return dict(rows)


# 오분류 신고 저장 (자동 반영은 안 하고, 나중에 검토용으로 쌓아둠)
def add_report(name: str, suggested_category: str, reason: str | None):
    with get_connection() as conn:
        cur = conn.cursor()
        cur.execute(
            "INSERT INTO ingredient_reports (name, suggested_category, reason, reported_at) VALUES (%s, %s, %s, %s)",
            (name, suggested_category, reason, time.time()),
        )
